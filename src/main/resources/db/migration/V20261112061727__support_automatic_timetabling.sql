-- Tổng tiết cũ chưa biết giữ NULL; không suy từ tín chỉ hoặc gán mặc định.
ALTER TABLE subjects ADD COLUMN total_teaching_periods INTEGER;
ALTER TABLE subjects ADD CONSTRAINT chk_subjects_teaching_periods
    CHECK (total_teaching_periods IS NULL OR total_teaching_periods > 0);

ALTER TABLE module_classes DROP CONSTRAINT chk_module_classes_status;
ALTER TABLE module_classes ADD CONSTRAINT chk_module_classes_status
    CHECK (status IN ('UNSCHEDULED', 'SCHEDULED', 'OPEN', 'CLOSED', 'COMPLETED', 'CANCELLED'));

-- Phương án nháp tách khỏi lịch chính thức; mỗi tác vụ chỉ lưu phương án tốt nhất hiện có.
CREATE TABLE timetable_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id BIGINT NOT NULL REFERENCES semesters(id),
    revision BIGINT NOT NULL DEFAULT 0,
    state VARCHAR(32) NOT NULL,
    input_fingerprint VARCHAR(64) NOT NULL,
    problem_json TEXT NOT NULL,
    allocation_json TEXT,
    diagnostics_json TEXT NOT NULL,
    hard_penalty BIGINT,
    soft_penalty BIGINT,
    expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    applied_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_timetable_plans_revision CHECK (revision >= 0),
    CONSTRAINT chk_timetable_plans_state CHECK (state IN (
        'QUEUED', 'RUNNING', 'STOP_REQUESTED', 'FEASIBLE', 'NO_FEASIBLE_SOLUTION',
        'STOPPED', 'FAILED', 'INTERRUPTED', 'APPLIED')),
    CONSTRAINT chk_timetable_plans_penalties CHECK (
        (hard_penalty IS NULL OR hard_penalty >= 0) AND (soft_penalty IS NULL OR soft_penalty >= 0)),
    CONSTRAINT chk_timetable_plans_feasible CHECK (
        state NOT IN ('FEASIBLE', 'APPLIED') OR
        (allocation_json IS NOT NULL AND hard_penalty IS NOT NULL AND hard_penalty = 0)),
    CONSTRAINT chk_timetable_plans_applied CHECK (state <> 'APPLIED' OR applied_at IS NOT NULL)
);

-- Chống hai request cạnh tranh cùng khởi tạo tác vụ; SolverManager cũng chỉ chạy một solver.
CREATE UNIQUE INDEX uk_timetable_plans_active_worker ON timetable_plans ((TRUE))
    WHERE is_deleted = FALSE AND state IN ('QUEUED', 'RUNNING', 'STOP_REQUESTED');
CREATE INDEX idx_timetable_plans_semester ON timetable_plans (semester_id, applied_at DESC)
    WHERE is_deleted = FALSE;
CREATE INDEX idx_timetable_plans_expiry ON timetable_plans (expires_at)
    WHERE is_deleted = FALSE AND state IN ('QUEUED', 'RUNNING', 'STOP_REQUESTED');
