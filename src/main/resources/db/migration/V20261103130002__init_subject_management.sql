CREATE TABLE subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_code TEXT NOT NULL,
    subject_name TEXT NOT NULL,
    credits INTEGER NOT NULL,
    description TEXT,
    status VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_subjects_code UNIQUE (subject_code),
    CONSTRAINT uk_subjects_name UNIQUE (subject_name),
    CONSTRAINT chk_subjects_credits_positive CHECK (credits > 0),
    CONSTRAINT chk_subjects_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE subject_prerequisites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id BIGINT NOT NULL REFERENCES subjects(id),
    prerequisite_subject_id BIGINT NOT NULL REFERENCES subjects(id),
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_subject_prerequisites_subject ON subject_prerequisites(subject_id);
CREATE INDEX idx_subject_prerequisites_prerequisite ON subject_prerequisites(prerequisite_subject_id);