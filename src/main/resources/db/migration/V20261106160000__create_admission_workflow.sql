-- Giữ nguyên sinh viên, tài khoản hiện có và các cột dữ liệu tuyển sinh cũ.
DROP INDEX uk_students_active_email_normalized;

ALTER TABLE cohorts ADD COLUMN code_sequence INTEGER CHECK (code_sequence BETWEEN 1 AND 99);
UPDATE cohorts SET code_sequence = SUBSTRING(cohort_code FROM '([0-9]{1,2})$')::INTEGER
WHERE cohort_code ~ '^[A-Za-z]+[0-9]{1,2}$'
  AND SUBSTRING(cohort_code FROM '([0-9]{1,2})$')::INTEGER BETWEEN 1 AND 99;
CREATE UNIQUE INDEX uk_cohorts_code_sequence ON cohorts(code_sequence) WHERE code_sequence IS NOT NULL;

ALTER TABLE administrative_classes
    ADD COLUMN reserve_capacity INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN last_student_sequence INTEGER NOT NULL DEFAULT 0,
    ADD CONSTRAINT chk_class_reserve CHECK (reserve_capacity >= 0 AND max_capacity + reserve_capacity <= 99),
    ADD CONSTRAINT chk_class_sequence CHECK (last_student_sequence BETWEEN 0 AND 99);

UPDATE administrative_classes c
SET last_student_sequence = COALESCE((
    SELECT MAX(RIGHT(s.student_code, 2)::INTEGER)
    FROM students s WHERE s.class_id = c.id AND s.student_code ~ '[0-9]{6}$'
), 0);

CREATE UNIQUE INDEX uk_administrative_class_scope_name
    ON administrative_classes (major_id, cohort_id, LOWER(class_name));

CREATE TABLE admission_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    major_id BIGINT NOT NULL REFERENCES majors(id),
    cohort_id BIGINT NOT NULL REFERENCES cohorts(id),
    total_students INTEGER NOT NULL CHECK (total_students >= 0),
    min_capacity INTEGER NOT NULL,
    max_capacity INTEGER NOT NULL,
    reserve_capacity INTEGER NOT NULL,
    selected_class_count INTEGER,
    state VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
    revision BIGINT NOT NULL DEFAULT 0,
    confirmation_token VARCHAR(36),
    processing_until TIMESTAMP,
    exception_reason VARCHAR(500),
    created_at TIMESTAMP, updated_at TIMESTAMP, created_by VARCHAR(255), updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_plan_capacities CHECK (
        min_capacity > 0 AND min_capacity <= max_capacity AND reserve_capacity >= 0
        AND max_capacity + reserve_capacity <= 99)
);

CREATE TABLE admission_plan_classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL REFERENCES admission_plans(id),
    class_id BIGINT NOT NULL UNIQUE REFERENCES administrative_classes(id),
    class_position INTEGER NOT NULL,
    target_size INTEGER NOT NULL CHECK (target_size BETWEEN 0 AND 99),
    created_at TIMESTAMP, updated_at TIMESTAMP, created_by VARCHAR(255), updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE(plan_id, class_position)
);

CREATE TABLE admission_applicants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL REFERENCES admission_plans(id),
    row_number INTEGER NOT NULL,
    application_code TEXT,
    citizen_id TEXT,
    full_name TEXT,
    date_of_birth DATE,
    gender TEXT,
    email TEXT,
    phone TEXT,
    entrance_score NUMERIC,
    state VARCHAR(24) NOT NULL,
    error_message VARCHAR(1000),
    warning_message VARCHAR(500),
    reuse_account BOOLEAN NOT NULL DEFAULT FALSE,
    class_id BIGINT REFERENCES administrative_classes(id),
    student_id BIGINT REFERENCES students(id),
    created_at TIMESTAMP, updated_at TIMESTAMP, created_by VARCHAR(255), updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE(plan_id, row_number)
);
CREATE INDEX idx_admission_applicants_plan ON admission_applicants(plan_id, state);

CREATE TABLE student_admissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_code VARCHAR(100) NOT NULL UNIQUE,
    student_id BIGINT NOT NULL REFERENCES students(id),
    plan_id BIGINT NOT NULL REFERENCES admission_plans(id),
    class_id BIGINT NOT NULL REFERENCES administrative_classes(id),
    citizen_id VARCHAR(12) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    date_of_birth DATE,
    gender VARCHAR(32),
    email VARCHAR(255),
    phone VARCHAR(32),
    entrance_score NUMERIC(19,2) NOT NULL,
    activity_status VARCHAR(32) NOT NULL DEFAULT 'STUDYING',
    created_at TIMESTAMP, updated_at TIMESTAMP, created_by VARCHAR(255), updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_student_admissions_student ON student_admissions(student_id);

CREATE TABLE admission_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admission_id BIGINT NOT NULL UNIQUE REFERENCES student_admissions(id),
    student_id BIGINT NOT NULL REFERENCES students(id),
    recipient VARCHAR(255),
    kind VARCHAR(24) NOT NULL,
    state VARCHAR(24) NOT NULL,
    failure_count INTEGER NOT NULL DEFAULT 0 CHECK (failure_count BETWEEN 0 AND 3),
    next_attempt_at TIMESTAMP NOT NULL,
    last_error VARCHAR(255),
    created_at TIMESTAMP, updated_at TIMESTAMP, created_by VARCHAR(255), updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_admission_notifications_retry ON admission_notifications(state, next_attempt_at);

ALTER TABLE students DROP CONSTRAINT chk_students_account_notification_status;
ALTER TABLE students ADD CONSTRAINT chk_students_account_notification_status
    CHECK (account_notification_status IS NULL OR account_notification_status IN ('PENDING','SENT','FAILED','SKIPPED'));
