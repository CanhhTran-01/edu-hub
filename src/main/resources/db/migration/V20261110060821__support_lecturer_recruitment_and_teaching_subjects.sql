-- Bộ đếm kỹ thuật tham gia transaction tạo hồ sơ, không bị giảm hoặc xóa khi hồ sơ xóa mềm.
CREATE TABLE lecturer_code_counters (
    faculty_id BIGINT NOT NULL REFERENCES faculties(id),
    recruitment_year INTEGER NOT NULL CHECK (recruitment_year BETWEEN 1000 AND 9999),
    last_lecturer_sequence INTEGER NOT NULL CHECK (last_lecturer_sequence BETWEEN 1 AND 999),
    PRIMARY KEY (faculty_id, recruitment_year)
);

CREATE FUNCTION prevent_allocated_faculty_code_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.faculty_code IS DISTINCT FROM NEW.faculty_code
       AND EXISTS (SELECT 1 FROM lecturer_code_counters WHERE faculty_id = OLD.id) THEN
        RAISE EXCEPTION 'Không được đổi mã khoa đã dùng cấp MSGV'
            USING ERRCODE = '23514', CONSTRAINT = 'chk_allocated_faculty_code_immutable';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_faculty_code_immutable
BEFORE UPDATE OF faculty_code ON faculties
FOR EACH ROW EXECUTE FUNCTION prevent_allocated_faculty_code_change();

-- People sở hữu liên kết; FK giữ toàn vẹn với danh mục Curriculum, không cascade xóa lịch sử.
CREATE TABLE lecturer_teaching_subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lecturer_id BIGINT NOT NULL REFERENCES lecturers(id),
    subject_id BIGINT NOT NULL REFERENCES subjects(id),
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_lecturer_teaching_subject UNIQUE (lecturer_id, subject_id)
);
CREATE INDEX idx_lecturer_teaching_subjects_subject_id ON lecturer_teaching_subjects(subject_id);
