-- Khởi tạo quản lý kỳ học và dữ liệu mẫu cho môi trường phát triển/test.
CREATE TABLE semesters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_code TEXT NOT NULL,
    semester_name TEXT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    registration_start DATE NOT NULL,
    registration_end DATE NOT NULL,
    is_locked BOOLEAN NOT NULL DEFAULT FALSE,
    locked_grade BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_semesters_code UNIQUE (semester_code),
    CONSTRAINT uk_semesters_name UNIQUE (semester_name),
    CONSTRAINT chk_semesters_name CHECK (
        semester_name ~ '^Học kì [1-9][0-9]* năm học [0-9]{4}-[0-9]{4}$'
    ),
    CONSTRAINT chk_semesters_code CHECK (
        semester_code = regexp_replace(
            semester_name,
            '^Học kì ([1-9][0-9]*) năm học ([0-9]{4})-([0-9]{4})$',
            'HK_\1_\2_\3'
        )
    ),
    CONSTRAINT chk_semesters_study_dates CHECK (start_date < end_date),
    CONSTRAINT chk_semesters_registration_dates CHECK (
        registration_start < registration_end AND registration_end < start_date
    ),
    -- Các khoảng ngày bao gồm cả hai đầu mút; chỉ bảo vệ kỳ chưa xóa mềm.
    CONSTRAINT ex_semesters_study_period EXCLUDE USING gist (
        daterange(start_date, end_date, '[]') WITH &&
    ) WHERE (is_deleted = FALSE),
    CONSTRAINT ex_semesters_registration_period EXCLUDE USING gist (
        daterange(registration_start, registration_end, '[]') WITH &&
    ) WHERE (is_deleted = FALSE)
);

