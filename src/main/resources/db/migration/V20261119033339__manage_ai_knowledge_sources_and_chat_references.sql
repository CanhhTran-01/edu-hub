-- Giữ nguyên hội thoại và snapshot trích dẫn cũ khi thống nhất tên bảng theo mô hình nghiệp vụ.
ALTER TABLE ai_chat_sessions RENAME TO chat_sessions;
ALTER TABLE ai_chat_messages RENAME TO chat_messages;
ALTER TABLE ai_chat_citations RENAME TO message_chunk_references;

ALTER TABLE chat_sessions
    ADD COLUMN title VARCHAR(255),
    ADD COLUMN started_at TIMESTAMP,
    ADD COLUMN last_message_at TIMESTAMP,
    ADD COLUMN topic_type VARCHAR(32) NOT NULL DEFAULT 'KNOWLEDGE';

ALTER TABLE chat_messages ADD COLUMN sent_at TIMESTAMP;
-- Audit cũ theo UTC; thời gian hội thoại là thời gian nghiệp vụ Việt Nam.
UPDATE chat_messages
SET sent_at = created_at AT TIME ZONE 'UTC' AT TIME ZONE 'Asia/Ho_Chi_Minh';
UPDATE chat_sessions session
SET title = COALESCE((
        SELECT left(message.content, 120) FROM chat_messages message
        WHERE message.session_id = session.id AND message.role = 'USER'
        ORDER BY message.id LIMIT 1
    ), 'Cuộc hội thoại'),
    started_at = session.created_at AT TIME ZONE 'UTC' AT TIME ZONE 'Asia/Ho_Chi_Minh',
    last_message_at = COALESCE((
        SELECT max(message.sent_at) FROM chat_messages message WHERE message.session_id = session.id
    ), session.created_at AT TIME ZONE 'UTC' AT TIME ZONE 'Asia/Ho_Chi_Minh');

CREATE INDEX idx_chat_sessions_user_started_at ON chat_sessions(user_id, started_at DESC, id DESC);

CREATE TABLE knowledge_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uploaded_by BIGINT REFERENCES users(id),
    prev_source_id BIGINT REFERENCES knowledge_sources(id),
    title TEXT NOT NULL,
    document_type VARCHAR(50),
    original_filename VARCHAR(255),
    original_file BYTEA,
    file_hash VARCHAR(64),
    uploaded_at TIMESTAMP,
    effective_date DATE,
    expiry_date DATE,
    status VARCHAR(16) NOT NULL CHECK (status IN ('PROCESSING', 'ACTIVE', 'INACTIVE', 'FAILED', 'DELETED')),
    error_message VARCHAR(500),
    embedding_model VARCHAR(255),
    embedding_model_version VARCHAR(255),
    processing_token VARCHAR(36),
    processing_started_at TIMESTAMP,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_knowledge_source_dates CHECK (expiry_date IS NULL OR expiry_date >= effective_date),
    CONSTRAINT chk_knowledge_source_previous CHECK (prev_source_id IS NULL OR prev_source_id <> id)
);
CREATE UNIQUE INDEX uk_knowledge_sources_file_hash ON knowledge_sources(file_hash)
    WHERE file_hash IS NOT NULL AND NOT is_deleted;
CREATE UNIQUE INDEX uk_knowledge_sources_current_successor ON knowledge_sources(prev_source_id)
    WHERE prev_source_id IS NOT NULL AND NOT is_deleted AND status IN ('PROCESSING', 'ACTIVE');
CREATE INDEX idx_knowledge_sources_processing ON knowledge_sources(status, id) WHERE NOT is_deleted;

-- Vector cũ không có hash, tệp gốc hoặc model/version đáng tin cậy nên giữ ở nguồn INACTIVE.
-- Admin phải nạp lại tệp để tạo nguồn có thể truy xuất; không tự gán model cho vector không rõ nguồn gốc.
INSERT INTO knowledge_sources(title, status)
SELECT DISTINCT COALESCE(NULLIF(metadata->>'source', ''), 'Nguồn cũ không có tên'), 'INACTIVE'
FROM vector_store;

ALTER TABLE vector_store RENAME TO knowledge_chunks;
ALTER TABLE knowledge_chunks DROP CONSTRAINT vector_store_pkey;
ALTER TABLE knowledge_chunks RENAME COLUMN id TO legacy_vector_id;
ALTER TABLE knowledge_chunks
    ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ADD COLUMN source_id BIGINT REFERENCES knowledge_sources(id),
    ADD COLUMN chunk_index INTEGER,
    ADD COLUMN embedding_model VARCHAR(255),
    ADD COLUMN embedding_model_version VARCHAR(255),
    ADD COLUMN token_count INTEGER,
    ADD COLUMN page_number INTEGER,
    ADD COLUMN section_title VARCHAR(255),
    ADD COLUMN created_at TIMESTAMP,
    ADD COLUMN updated_at TIMESTAMP,
    ADD COLUMN created_by VARCHAR(255),
    ADD COLUMN updated_by VARCHAR(255),
    ADD COLUMN is_deleted BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE knowledge_chunks ALTER COLUMN legacy_vector_id DROP DEFAULT;
ALTER TABLE knowledge_chunks ALTER COLUMN legacy_vector_id DROP NOT NULL;

UPDATE knowledge_chunks chunk
SET source_id = source.id,
    section_title = chunk.metadata->>'sectionTitle'
FROM knowledge_sources source
WHERE source.title = COALESCE(NULLIF(chunk.metadata->>'source', ''), 'Nguồn cũ không có tên');
-- Thứ tự chunk cũ cũng không được lưu: để NULL, không suy thứ tự tài liệu từ UUID hoặc vị trí vật lý.
ALTER TABLE knowledge_chunks ALTER COLUMN source_id SET NOT NULL;
ALTER TABLE knowledge_chunks ADD CONSTRAINT uk_knowledge_chunks_source_index UNIQUE(source_id, chunk_index);
ALTER TABLE knowledge_chunks ADD CONSTRAINT chk_knowledge_chunks_index CHECK (chunk_index IS NULL OR chunk_index >= 0);
ALTER TABLE knowledge_chunks ADD CONSTRAINT chk_knowledge_chunks_tokens CHECK (token_count IS NULL OR token_count > 0);
CREATE UNIQUE INDEX uk_knowledge_chunks_legacy_vector ON knowledge_chunks(legacy_vector_id);
CREATE INDEX idx_knowledge_chunks_source ON knowledge_chunks(source_id);
ALTER INDEX vector_store_embedding_hnsw_idx RENAME TO knowledge_chunks_embedding_hnsw_idx;

