-- Enrollment giữ các lượt học thật; không tạo lịch sử hoặc điểm giả cho khóa chưa chuyển dữ liệu.
ALTER TABLE module_classes ADD CONSTRAINT uk_module_classes_enrollment_reference UNIQUE (id, subject_id, semester_id);

CREATE TABLE enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    module_class_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    semester_id BIGINT NOT NULL,
    subject_code TEXT NOT NULL,
    subject_name TEXT NOT NULL,
    module_class_code TEXT NOT NULL,
    academic_year_start INTEGER NOT NULL CHECK (academic_year_start BETWEEN 1000 AND 9999),
    semester_number INTEGER NOT NULL CHECK (semester_number > 0),
    credits INTEGER NOT NULL CHECK (credits > 0),
    registered_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    dropped_at TIMESTAMP WITHOUT TIME ZONE,
    status VARCHAR(32) NOT NULL CHECK (status IN ('REGISTERED', 'DROPPED', 'COMPLETED', 'FAILED')),
    component_score_1 NUMERIC(6,3) CHECK (component_score_1 BETWEEN 0 AND 10),
    component_score_2 NUMERIC(6,3) CHECK (component_score_2 BETWEEN 0 AND 10),
    process_score NUMERIC(3,1) CHECK (process_score BETWEEN 0 AND 10),
    final_exam_score NUMERIC(6,3) CHECK (final_exam_score BETWEEN 0 AND 10),
    course_score_grade_10 NUMERIC(3,1) CHECK (course_score_grade_10 BETWEEN 0 AND 10),
    course_score_grade_letter VARCHAR(2) CHECK (course_score_grade_letter IN ('A+', 'A', 'B+', 'B', 'C+', 'C', 'D+', 'D', 'F')),
    course_score_grade_4 NUMERIC(2,1) CHECK (course_score_grade_4 BETWEEN 0 AND 4),
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_enrollments_module_class FOREIGN KEY (module_class_id, subject_id, semester_id) REFERENCES module_classes(id, subject_id, semester_id),
    CONSTRAINT chk_enrollments_drop CHECK ((status = 'DROPPED') = (dropped_at IS NOT NULL)),
    CONSTRAINT chk_enrollments_result CHECK (
        (status IN ('REGISTERED', 'DROPPED') AND course_score_grade_10 IS NULL
            AND course_score_grade_letter IS NULL AND course_score_grade_4 IS NULL)
        OR (status = 'COMPLETED' AND course_score_grade_10 IS NOT NULL AND course_score_grade_10 >= 4
            AND course_score_grade_letter IS NOT NULL AND course_score_grade_letter <> 'F'
            AND course_score_grade_4 IS NOT NULL AND course_score_grade_4 > 0)
        OR (status = 'FAILED' AND course_score_grade_10 IS NOT NULL AND course_score_grade_10 < 4
            AND course_score_grade_letter IS NOT NULL AND course_score_grade_letter = 'F'
            AND course_score_grade_4 IS NOT NULL AND course_score_grade_4 = 0)
    )
);

-- Chỉ một đăng ký hiệu lực cho mỗi môn/kỳ; lịch sử hủy không ngăn đăng ký lại lớp khác.
CREATE UNIQUE INDEX uk_enrollments_active_subject_semester ON enrollments(student_id, subject_id, semester_id)
    WHERE status = 'REGISTERED' AND NOT is_deleted;
CREATE INDEX idx_enrollments_module_class ON enrollments(module_class_id);
CREATE INDEX idx_enrollments_student_history ON enrollments(student_id, academic_year_start, semester_number);

