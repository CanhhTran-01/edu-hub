-- Lớp học phần thuộc scheduling. Chỉ tạo schema, chưa seed lớp khi chưa có nguồn giảng viên.
CREATE TABLE module_classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_class_code TEXT NOT NULL,
    semester_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    -- ID hồ sơ Lecturer, không phải User ID dù Lecturer và User có quan hệ 1-1.
    -- TODO(PEOPLE_INTEGRATION): thêm FK lecturers(id) khi BE1 cung cấp schema/nguồn ID thật.
    lecturer_id BIGINT NOT NULL,
    class_sequence INTEGER NOT NULL,
    max_capacity INTEGER NOT NULL DEFAULT 80,
    current_size INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(255) NOT NULL DEFAULT 'UNSCHEDULED',
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_module_classes_code UNIQUE (module_class_code),
    -- Giữ STT đã cấp, kể cả khi lớp đã hủy hoặc soft delete.
    CONSTRAINT uk_module_classes_sequence UNIQUE (semester_id, subject_id, class_sequence),
    CONSTRAINT fk_module_classes_semester FOREIGN KEY (semester_id) REFERENCES semesters(id),
    CONSTRAINT fk_module_classes_subject FOREIGN KEY (subject_id) REFERENCES subjects(id),
    CONSTRAINT chk_module_classes_sequence CHECK (class_sequence > 0),
    -- TODO(CAPACITY_CONFIG): khi có cấu hình động, đồng bộ validation và constraint này.
    CONSTRAINT chk_module_classes_capacity CHECK (max_capacity BETWEEN 1 AND 80),
    CONSTRAINT chk_module_classes_current_size CHECK (current_size >= 0 AND current_size <= max_capacity),
    CONSTRAINT chk_module_classes_status CHECK (status IN ('UNSCHEDULED', 'SCHEDULED', 'OPEN', 'CANCELLED'))
);

CREATE INDEX idx_module_classes_semester_subject ON module_classes(semester_id, subject_id);
CREATE INDEX idx_module_classes_lecturer_semester ON module_classes(lecturer_id, semester_id);

