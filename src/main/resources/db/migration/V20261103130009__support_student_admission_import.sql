ALTER TABLE administrative_classes
    ALTER COLUMN major_code SET NOT NULL,
    ADD CONSTRAINT chk_administrative_class_capacity
        CHECK (min_capacity >= 0 AND max_capacity > 0 AND min_capacity <= max_capacity);

ALTER TABLE students
    ADD COLUMN admission_application_code VARCHAR(100),
    ADD COLUMN gender VARCHAR(32);

CREATE UNIQUE INDEX uk_students_admission_application_code
    ON students (admission_application_code)
    WHERE admission_application_code IS NOT NULL AND is_deleted = FALSE;

CREATE INDEX idx_administrative_classes_admission_scope
    ON administrative_classes (major_code, cohort_id, training_type)
    WHERE is_deleted = FALSE;

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(255),
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(100) NOT NULL,
    entity_id VARCHAR(255),
    details TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);
