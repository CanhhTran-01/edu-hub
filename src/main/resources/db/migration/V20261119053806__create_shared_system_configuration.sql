-- Danh mục khóa cố định; giá trị NULL dùng YAML/môi trường cho tới lần quản trị thiết lập đầu tiên.
-- Không sao chép secret hoặc tự đặt giới hạn tín chỉ khi chưa có quy chế chính thức.
CREATE TABLE system_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_key VARCHAR(255) NOT NULL,
    config_value TEXT,
    revision BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_system_configs_key UNIQUE (config_key),
    CONSTRAINT chk_system_configs_revision CHECK (revision >= 0)
);

