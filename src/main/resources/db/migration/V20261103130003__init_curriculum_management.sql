CREATE TABLE majors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    major_code TEXT NOT NULL,
    major_name TEXT NOT NULL,
    status VARCHAR(255) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT uk_majors_code UNIQUE (major_code),
    CONSTRAINT uk_majors_name UNIQUE (major_name),
    CONSTRAINT chk_majors_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- Các CTĐT(curriculum) tại version này chưa gắn với khóa tuyển sinh (cohort) cụ thể.
-- Không tạo bảng People hoặc tham chiếu cohort_id giả khi schema của BE1 chưa có.
-- Tổng tín chỉ được tính động từ curriculum_subjects, không lưu field riêng trong curriculums.
CREATE TABLE curriculums (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curriculum_code TEXT NOT NULL,
    curriculum_name TEXT NOT NULL,

    major_id BIGINT NOT NULL,
    -- TODO(PEOPLE_INTEGRATION): gắn CTĐT với Cohort từ BE1, "cohort_id BIGINT NOT NULL".

    training_type VARCHAR(255) NOT NULL DEFAULT 'CHINH_QUY',
    duration_semesters INTEGER NOT NULL DEFAULT 8,
    status VARCHAR(255) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT uk_curriculums_code UNIQUE (curriculum_code),
    CONSTRAINT fk_curriculums_major FOREIGN KEY (major_id) REFERENCES majors(id),
    CONSTRAINT chk_curriculums_training_type CHECK (training_type IN ('CHINH_QUY', 'LIEN_THONG', 'VAN_BANG_2')),
    CONSTRAINT chk_curriculums_duration CHECK (duration_semesters > 0),
    CONSTRAINT chk_curriculums_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- recommend_semester là chỉ số kỳ trong lộ trình (1,2,3,...), không phải ID của Semester.
-- Một học phần (subject) có thể thuộc ở các kỳ khác nhau trong các CTĐT (curriculum) khác nhau.
CREATE TABLE curriculum_subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curriculum_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    recommend_semester INTEGER NOT NULL,
    subject_type VARCHAR(255) NOT NULL DEFAULT 'REQUIRED',
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT uk_curriculum_subjects_pair UNIQUE (curriculum_id, subject_id),
    CONSTRAINT fk_curriculum_subjects_curriculum FOREIGN KEY (curriculum_id) REFERENCES curriculums(id),
    CONSTRAINT fk_curriculum_subjects_subject FOREIGN KEY (subject_id) REFERENCES subjects(id),
    CONSTRAINT chk_curriculum_subjects_semester CHECK (recommend_semester > 0),

    -- TODO: tất cả học phần trong CTĐT là bắt buộc; môn tự chọn (ELECTIVE) sẽ được bổ sung sau.
    CONSTRAINT chk_curriculum_subjects_type CHECK (subject_type = 'REQUIRED')
);

CREATE INDEX idx_curriculums_major ON curriculums(major_id);
CREATE INDEX idx_curriculum_subjects_subject ON curriculum_subjects(subject_id);
CREATE INDEX idx_curriculum_subjects_recommend_semester
    ON curriculum_subjects(curriculum_id, recommend_semester) WHERE is_deleted = FALSE;