-- Khởi tạo bảng phòng học (rooms) và lịch học (class_schedules).
-- Bao gồm khóa ngoại, CHECK, index và trigger kiểm tra trạng thái/sức chứa phòng khi lưu lịch.
CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_code VARCHAR(50) NOT NULL,
    room_name VARCHAR(255) NOT NULL,
    campus VARCHAR(100) NOT NULL DEFAULT '',
    building_code VARCHAR(50) NOT NULL,
    room_number VARCHAR(50) NOT NULL,
    capacity INTEGER NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,

    -- Mã phòng và vị trí vẫn được giữ sau khi xóa mềm, không được tái sử dụng.
    CONSTRAINT uk_rooms_code UNIQUE (room_code),
    CONSTRAINT uk_rooms_location UNIQUE (campus, building_code, room_number),
    CONSTRAINT chk_rooms_capacity CHECK (capacity > 0),
    CONSTRAINT chk_rooms_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT chk_rooms_identifiers CHECK (
        length(btrim(room_code)) > 0 AND room_code = btrim(room_code)
        AND length(btrim(building_code)) > 0 AND building_code = btrim(building_code)
        AND length(btrim(room_number)) > 0 AND room_number = btrim(room_number)
    ),
    CONSTRAINT chk_rooms_details CHECK (length(btrim(room_name)) > 0)
);

-- tạo bảng lịch học để kiểm tra ràng buộc A2/A3 trong use-case quản lý phòng.
-- luồng xếp lịch sẽ được triển khai sau.
CREATE TABLE class_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_class_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    day_of_week INTEGER NOT NULL,
    lesson_order_start INTEGER NOT NULL,
    lesson_order_end INTEGER NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    updated_at TIMESTAMP WITHOUT TIME ZONE,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_class_schedules_module_class FOREIGN KEY (module_class_id) REFERENCES module_classes(id),
    CONSTRAINT fk_class_schedules_room FOREIGN KEY (room_id) REFERENCES rooms(id),
    CONSTRAINT chk_class_schedules_day CHECK (day_of_week BETWEEN 2 AND 8),
    CONSTRAINT chk_class_schedules_lessons CHECK (lesson_order_start > 0 AND lesson_order_end >= lesson_order_start),
    CONSTRAINT chk_class_schedules_dates CHECK (start_date <= end_date)
);

CREATE INDEX idx_class_schedules_room ON class_schedules(room_id) WHERE is_deleted = FALSE;
CREATE INDEX idx_class_schedules_module_class ON class_schedules(module_class_id);

-- Khóa hàng phòng để đồng bộ việc lưu lịch với cập nhật, ngừng sử dụng và xóa mềm phòng.
-- Từ chối lịch dùng phòng ngừng sử dụng, đã xóa hoặc không đủ sức chứa.
CREATE FUNCTION require_available_schedule_room() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE
    selected_room rooms%ROWTYPE;
    required_capacity INTEGER;
BEGIN
    IF NEW.is_deleted THEN
        RETURN NEW;
    END IF;
    SELECT * INTO selected_room FROM rooms WHERE id = NEW.room_id FOR UPDATE;
    IF NOT FOUND THEN
        RETURN NEW; -- Khóa ngoại sẽ báo lỗi khi phòng không tồn tại.
    END IF;
    IF selected_room.is_deleted OR selected_room.status <> 'ACTIVE' THEN
        RAISE EXCEPTION 'Room is not available for scheduling'
            USING ERRCODE = '23514', CONSTRAINT = 'chk_class_schedules_room_available';
    END IF;
    SELECT max_capacity INTO required_capacity FROM module_classes WHERE id = NEW.module_class_id;
    IF selected_room.capacity < required_capacity THEN
        RAISE EXCEPTION 'Room capacity is below class capacity'
            USING ERRCODE = '23514', CONSTRAINT = 'chk_class_schedules_room_capacity';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_class_schedules_available_room
BEFORE INSERT OR UPDATE ON class_schedules
FOR EACH ROW EXECUTE FUNCTION require_available_schedule_room();