CREATE TABLE cohorts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cohort_code VARCHAR(255) NOT NULL,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE administrative_classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_name VARCHAR(255) NOT NULL,
    major_id BIGINT NOT NULL,
    major_name VARCHAR(255) NOT NULL,
    cohort_id BIGINT NOT NULL REFERENCES cohorts(id),
    training_type VARCHAR(32) NOT NULL,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    class_id BIGINT REFERENCES administrative_classes(id),
    student_code VARCHAR(255) NOT NULL UNIQUE,
    full_name VARCHAR(255) NOT NULL,
    citizen_id VARCHAR(255),
    date_of_birth DATE,
    email VARCHAR(255),
    phone VARCHAR(255),
    entrance_score NUMERIC(19, 2),
    target_gpa NUMERIC(19, 2),
    activity_status VARCHAR(32) NOT NULL,
    academic_warning_status VARCHAR(255),
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE faculties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_name VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE lecturers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    faculty_id BIGINT REFERENCES faculties(id),
    lecturer_code VARCHAR(255) NOT NULL UNIQUE,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    phone VARCHAR(255),
    date_of_birth DATE,
    citizen_id VARCHAR(255),
    account_notification_status VARCHAR(16),
    account_notification_error TEXT,
    status VARCHAR(32) NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT chk_lecturer_notification_status CHECK (account_notification_status IN ('PENDING', 'SENT', 'FAILED'))
);

CREATE INDEX idx_administrative_classes_major_id ON administrative_classes (major_id);
CREATE INDEX idx_administrative_classes_cohort_id ON administrative_classes (cohort_id);
CREATE INDEX idx_students_class_id ON students (class_id);
CREATE INDEX idx_students_user_id ON students (user_id);
CREATE INDEX idx_lecturers_faculty_id ON lecturers (faculty_id);
CREATE INDEX idx_lecturers_user_id ON lecturers (user_id);
CREATE UNIQUE INDEX uk_lecturers_email_active ON lecturers (lower(trim(email)))WHERE is_deleted = FALSE AND email IS NOT NULL;
CREATE UNIQUE INDEX uk_lecturers_citizen_id_active ON lecturers (citizen_id)WHERE is_deleted = FALSE AND citizen_id IS NOT NULL;

