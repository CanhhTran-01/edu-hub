INSERT INTO curriculums (curriculum_code, curriculum_name, major_id, cohort_id, training_type,
                         duration_semesters, required_graduation_credits, status,
                         created_at, updated_at, created_by, updated_by)
SELECT 'CTDT-' || CASE major.major_code WHEN 'CNTT' THEN 'CT' WHEN 'ATTT' THEN 'AT'
                       WHEN 'DTVT' THEN 'DT' ELSE 'AI' END || '-' || cohort.cohort_code || '-CQ',
       'Chương trình ' || major.major_name || ' khóa ' || cohort.start_year,
       major.id, cohort.id, 'CHINH_QUY', 8, graduation.required_credits, 'ACTIVE',
       make_date(cohort.start_year, 6, 1)::TIMESTAMP, make_date(cohort.start_year, 6, 1)::TIMESTAMP,
       'demo-seed', 'demo-seed'
FROM majors major CROSS JOIN cohorts cohort
JOIN LATERAL (
    SELECT sum(subject.credits)::INTEGER AS required_credits
    FROM demo_curriculum_path curriculum_path JOIN subjects subject ON subject.subject_code = curriculum_path.subject_code
    WHERE curriculum_path.major_code = major.major_code
) graduation ON TRUE
WHERE major.major_code <> 'TTNT' OR cohort.start_year >= 2021
ORDER BY cohort.start_year, major.major_code;

INSERT INTO curriculum_subjects (curriculum_id, subject_id, recommend_semester, subject_type,
                                 created_at, updated_at, created_by, updated_by)
SELECT curriculum.id, subject.id, curriculum_path.recommend_semester, 'REQUIRED',
       curriculum.created_at, curriculum.updated_at, 'demo-seed', 'demo-seed'
FROM curriculums curriculum JOIN majors major ON major.id = curriculum.major_id
JOIN demo_curriculum_path curriculum_path ON curriculum_path.major_code = major.major_code
JOIN subjects subject ON subject.subject_code = curriculum_path.subject_code;
